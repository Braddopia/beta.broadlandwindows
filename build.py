#!/usr/bin/env python3
"""Build Broadland CRM into one self-contained HTML file.

    python3 build.py   ->  dist/Broadland-Windows-CRM-<version>.html and index.html

src/index.html      page skeleton (placeholders <!-- @@CSS@@ --> and <!-- @@JS@@ -->)
src/css/*.css       styles, joined in filename order
src/js/*.js         app code, joined in filename order (one shared scope)
src/assets/*.txt    base64 data-URI images, exposed to JS as ASSETS.<camelCaseName>
src/boot-loader.js  small start-up script: reads the saved data from IndexedDB, then runs the app

The app code is stored in <script type="text/plain" id="appjs"> so it does not run until
the loader has the saved data ready.
"""
import json, pathlib, re, shutil, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent
SRC, DIST = ROOT / "src", ROOT / "dist"
VERSION = "v19.2"
NAME = "Broadland-Windows-CRM"
U8 = "utf-8"  # always UTF-8, so '£' and other symbols survive on Windows too


def camel(stem):
    a, *b = stem.split("-")
    return a + "".join(w.title() for w in b)


def fail(msg):
    sys.exit(f"Build failed: {msg}")


def read_all(folder, pattern):
    files = sorted((SRC / folder).glob(pattern))
    if not files:
        fail(f"no {pattern} files in src/{folder}")
    return files


def check_inline(text, where, bad_list=("</script", "<!--")):
    """Text placed inside a <script> (or <style>) block must not be able to close it early."""
    low = text.lower()
    for bad in bad_list:
        if bad in low:
            line = low[: low.index(bad)].count("\n") + 1
            fail(f"{where} contains '{bad}' near line {line}, which would break the page")


def check_syntax(js, name):
    """Catch a typo in one module before it ships as a blank page (needs Node; skipped if missing)."""
    node = shutil.which("node")
    if not node:
        return
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding=U8) as f:
        f.write(js)
    try:
        r = subprocess.run([node, "--check", f.name], capture_output=True, text=True)
    finally:
        pathlib.Path(f.name).unlink(missing_ok=True)
    if r.returncode:
        fail(f"{name} has a syntax error:\n{r.stderr.strip()}")


def place(html, marker, block):
    if html.count(marker) != 1:
        fail(f"src/index.html must contain {marker} exactly once")
    return html.replace(marker, block)


def main():
    css = "\n".join(p.read_text(encoding=U8) for p in read_all("css", "*.css"))
    check_inline(css, "the CSS", ("</style",))

    assets = {}
    for p in sorted((SRC / "assets").glob("*.txt")):
        v = p.read_text(encoding=U8).strip()
        if not re.fullmatch(r"data:image/(png|jpeg|webp|svg\+xml);base64,[A-Za-z0-9+/=]+", v):
            fail(f"src/assets/{p.name} is not a base64 image data URI")
        assets[camel(p.stem)] = v

    parts = ["/* 00 · Embedded images (generated by build.py from src/assets) */\nconst ASSETS=" + json.dumps(assets) + ";"]
    for p in read_all("js", "*.js"):
        t = p.read_text(encoding=U8)
        check_inline(t, f"src/js/{p.name}")
        parts.append(t)
    js = "\n".join(parts)
    check_syntax(js, "the app code (src/js)")

    loader = (SRC / "boot-loader.js").read_text(encoding=U8)
    check_inline(loader, "src/boot-loader.js")
    check_syntax(loader, "src/boot-loader.js")

    html = (SRC / "index.html").read_text(encoding=U8)
    html = place(html, "<!-- @@CSS@@ -->", f"<style>\n/* Broadland Windows CRM {VERSION} */\n{css}</style>")
    html = place(html, "<!-- @@JS@@ -->",
                 f'<script type="text/plain" id="appjs">\n{js}\n</script>\n<script>\n{loader}\n</script>')

    DIST.mkdir(exist_ok=True)
    out = DIST / f"{NAME}-{VERSION}.html"
    for old in DIST.glob(f"{NAME}-*.html"):  # drop builds of older versions so only one file ships
        if old != out:
            old.unlink()
    out.write_text(html, encoding=U8, newline="\n")
    (ROOT / "index.html").write_text(html, encoding=U8, newline="\n")  # served copy (GitHub Pages)
    print(f"Built {out.relative_to(ROOT)} and index.html ({out.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
