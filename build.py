#!/usr/bin/env python3
"""Build Broadland CRM into one self-contained HTML file.

    python3 build.py            ->  dist/broadland-crm-<version>.html and index.html

src/index.html   page skeleton (placeholders <!-- @@CSS@@ --> and <!-- @@JS@@ -->)
src/css/*.css    styles, concatenated in filename order
src/js/*.js      scripts, concatenated in filename order (one shared scope)
src/assets/*.txt base64 data-URI images, exposed to JS as ASSETS.<camelCaseName>
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent
SRC, DIST = ROOT / "src", ROOT / "dist"
VERSION = "v19.2"
NAME = "Broadland-Windows-CRM"

def camel(stem):
    a, *b = stem.split("-")
    return a + "".join(w.title() for w in b)

def main():
    css = "\n".join(p.read_text() for p in sorted((SRC / "css").glob("*.css")))
    assets = {camel(p.stem): p.read_text().strip() for p in sorted((SRC / "assets").glob("*.txt"))}
    for k, v in assets.items():
        assert re.fullmatch(r"data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+", v), k
    js = "/* 00 · Embedded images (generated by build.py from src/assets) */\nconst ASSETS=" + json.dumps(assets) + ";\n"
    js += "\n".join(p.read_text() for p in sorted((SRC / "js").glob("*.js")))
    assert "</script" not in js.lower(), "a JS file contains </script>, which would break the page"
    html = (SRC / "index.html").read_text()
    html = html.replace("<!-- @@CSS@@ -->", f"<style>\n/* Broadland Windows CRM {VERSION} */\n{css}</style>")
    loader = (SRC / "boot-loader.js").read_text()
    assert "</script" not in loader.lower()
    html = html.replace("<!-- @@JS@@ -->", f"<script type=\"text/plain\" id=\"appjs\">\n{js}\n</script>\n<script>\n{loader}\n</script>")
    DIST.mkdir(exist_ok=True)
    out = DIST / f"{NAME}-{VERSION}.html"
    out.write_text(html)
    (ROOT / "index.html").write_text(html)  # served copy for hosting (e.g. GitHub Pages)
    print(f"Built {out.relative_to(ROOT)} and index.html ({out.stat().st_size/1024:.0f} KB)")

if __name__ == "__main__":
    main()
