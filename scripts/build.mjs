#!/usr/bin/env node
/**
 * Build the Broadland CRM into one self-contained HTML file.
 *
 *   npm run build   ->  dist/Broadland-Windows-CRM-<version>.html  and  index.html (GitHub Pages)
 *
 * Inputs
 *   src/index.html       page skeleton with the placeholders <!-- @@CSS@@ --> and <!-- @@JS@@ -->
 *   src/css/*.css        styles, joined in file-name order
 *   src/main.js          app entry point; esbuild bundles it and every module it imports
 *   src/assets/*.txt     base64 image data URIs, exposed to the app as ASSETS.<camelCaseName>
 *   src/boot-loader.js   start-up script: loads saved data from IndexedDB, then runs the app
 *
 * The app code sits in <script type="text/plain" id="appjs"> so it doesn't run until the loader
 * has the saved data ready.
 *
 * Safety checks (the build stops with a clear message if one fails):
 *   - each placeholder appears exactly once in the skeleton
 *   - assets really are base64 image data URIs
 *   - no inlined code can close its own <script>/<style> block early
 *   - the JavaScript parses (esbuild syntax check), so a typo can't ship as a blank page
 *
 * Security: the page's Content-Security-Policy allows only these two exact scripts (by SHA-256 hash)
 * instead of 'unsafe-inline', so injected <script> tags or inline event handlers can never run.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, unlinkSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync, buildSync } from 'esbuild';
import { createHash } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const VERSION = 'v' + pkg.version.split('.').slice(0, 2).join('.');
const NAME = 'Broadland-Windows-CRM';

const fail = (msg) => {
  console.error('Build failed: ' + msg);
  process.exit(1);
};
const read = (p) => readFileSync(p, 'utf8');
const camel = (stem) =>
  stem
    .split('-')
    .map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w))
    .join('');

function filesIn(folder, ext) {
  const dir = join(SRC, folder);
  const names = readdirSync(dir)
    .filter((n) => n.endsWith(ext))
    .sort();
  if (!names.length) fail(`no *${ext} files in src/${folder}`);
  return names.map((n) => ({ name: n, path: join(dir, n) }));
}

/** text placed inside a <script> or <style> block must not be able to close it early */
function checkInline(text, where, bad = ['</script', '<!--']) {
  const low = text.toLowerCase();
  for (const b of bad) {
    const i = low.indexOf(b);
    if (i >= 0)
      fail(`${where} contains '${b}' near line ${low.slice(0, i).split('\n').length}, which would break the page`);
  }
}

/** catch a typo before it ships as a blank page */
function checkSyntax(code, where) {
  try {
    transformSync(code, { loader: 'js', logLevel: 'silent' });
  } catch (e) {
    const m = e.errors && e.errors[0];
    fail(`${where} has a syntax error${m ? ` at line ${m.location?.line}: ${m.text}` : ''}`);
  }
}

function place(html, marker, block) {
  if (html.split(marker).length !== 2) fail(`src/index.html must contain ${marker} exactly once`);
  return html.replace(marker, () => block);
}

// ---- styles ----
const css = filesIn('css', '.css')
  .map((f) => read(f.path))
  .join('\n');
checkInline(css, 'the CSS', ['</style']);

// ---- embedded images ----
const assets = {};
for (const f of readdirSync(join(SRC, 'assets'))
  .filter((n) => n.endsWith('.txt'))
  .sort()) {
  const v = read(join(SRC, 'assets', f)).trim();
  if (!/^data:image\/(png|jpeg|webp|svg\+xml);base64,[A-Za-z0-9+/=]+$/.test(v))
    fail(`src/assets/${f} is not a base64 image data URI`);
  assets[camel(f.replace(/\.txt$/, ''))] = v;
}

// ---- app code ----
let bundle;
try {
  bundle = buildSync({
    entryPoints: [join(SRC, 'main.js')],
    bundle: true,
    write: false,
    format: 'iife',
    target: 'es2020',
    charset: 'utf8',
    minifyWhitespace: true, // smaller file; names are kept so errors stay readable
    legalComments: 'none',
    logLevel: 'silent',
    banner: {
      js:
        '/* Embedded images (generated by the build from src/assets) */\nconst ASSETS=' + JSON.stringify(assets) + ';',
    },
  });
} catch (e) {
  const m = e.errors && e.errors[0];
  fail(`the app code has an error${m ? ` in ${m.location?.file}:${m.location?.line}: ${m.text}` : ''}`);
}
const js = bundle.outputFiles[0].text;
checkInline(js, 'the bundled app code');
checkSyntax(js, 'the bundled app code');

const loader = read(join(SRC, 'boot-loader.js'));
checkInline(loader, 'src/boot-loader.js');
checkSyntax(loader, 'src/boot-loader.js');

// ---- page ----
let html = read(join(SRC, 'index.html'));
html = place(html, '<!-- @@CSS@@ -->', `<style>\n/* Broadland Windows CRM ${VERSION} */\n${css}</style>`);
const appText = `\n${js}\n`,
  loaderText = `\n${loader}\n`;
const sha = (s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;
html = place(html, '@@SCRIPT_HASHES@@', `${sha(loaderText)} ${sha(appText)}`);
html = place(
  html,
  '<!-- @@JS@@ -->',
  `<script type="text/plain" id="appjs">${appText}</script>\n<script>${loaderText}</script>`
);

mkdirSync(DIST, { recursive: true });
const out = join(DIST, `${NAME}-${VERSION}.html`);
for (const old of readdirSync(DIST)) {
  // only one build ships: drop older versions
  if (old.startsWith(NAME + '-') && old.endsWith('.html') && join(DIST, old) !== out) unlinkSync(join(DIST, old));
}
writeFileSync(out, html);
writeFileSync(join(ROOT, 'index.html'), html);
console.log(`Built ${relative(ROOT, out)} and index.html (${Math.round(statSync(out).size / 1024)} KB)`);
