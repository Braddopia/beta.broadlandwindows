const row = (p, extra) => ({
  pid: p[0],
  item: p[1],
  desc: p[2],
  group: p[3],
  unit: p[4],
  length: p[5],
  cInName: p[6],
  cIn: hex(p[6]),
  cOutName: p[7],
  cOut: hex(p[7]),
  stock: p[8],
  cost: p[9],
  location: p[10],
  area: p[11],
  supplier: p[12],
  reorder: p[13],
  ...extra,
});

/** the sample movement log (newest first) and the bar lengths for the Cutting Optimiser */
export function sampleStock() {
  const byId = Object.fromEntries(PRODUCTS.map((p) => [p[0], p]));
  /* stock before this morning: the stock now, less what came in, plus what went out */
  const before = Object.fromEntries(PRODUCTS.map((p) => [p[0], p[8]]));
  for (const [, type, , , qty, id] of MOVES) before[id] += type == 'add' ? -qty : type == 'remove' ? qty : 0;
  const after = { ...before },
    moves = MOVES.slice()
      .reverse()
      .map(([time, type, flag, user, qty, id, job]) => {
        if (type == 'add') after[id] += qty;
        if (type == 'remove') after[id] -= qty;
        return row(byId[id], { time, type, flag, user, qty, stock: after[id], ...(job ? { job } : {}) });
      })
      .reverse();
  const opening = PRODUCTS.map((p) =>
    row(p, {
      time: '1 Nov',
      type: 'import',
      flag: false,
      user: 'Stock Controller',
      qty: before[p[0]],
      stock: before[p[0]],
    })
  );
  const bars = Object.fromEntries(
    PRODUCTS.filter((p) => /^\d+(\.\d+)?M$/.test(p[5])).map((p) => [p[0], { bar: Math.round(parseFloat(p[5]) * 1000) }])
  );
  return { items: [...moves, ...opening], cutProf: bars };
}
